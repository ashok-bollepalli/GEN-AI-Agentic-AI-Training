a = 10
b = 2

# Arithematic Operators
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b) ## quotient
print(a % b)  ## reminder

x = 5
print(x)
x += 5 # x = x + 5
print(x)

x -= 3 # x = x - 3
print(x)

# Relational Operators
i = 20
j = 20
print(i == j)
print(i != j)
print( i > j)

# Logical Operators

age = 25
salary = 30000

print(age > 18 and salary > 25000)
print(age > 18 or salary > 40000)

## Membership Operators
students = ["Ashok" , "Raju", "Rani"]
print("Ashok" in students)
print("Kiran" in students)
print("Anil" not in students)

# Identity Operators
a = 20
b = 20

print(a is b)
print(a is not b)